extern u8 gui_disp_char(const GUI_CHARINFO *CharInfo, u16 charinfo_num, u8 *dest_buff, u16 c, u16 x);
/**
 * 填充水印
 */
void watermark_put_str(u8* txt)
{
    u16 x_offs = 0;
    memset(watermark_buff, 0, sizeof(watermark_buff));
    while(*txt != 0){
        x_offs += gui_disp_char(Font32B_ASCII_CharInfo, CHARINFO_NUM, watermark_buff, *txt, x_offs);
        txt++;
        if(x_offs >= WATERMARK_WIDTH*8){
            break;
        }
    }
}


/**
 * 获取水印buff
 */
u8* watermark_get_buff(void)
{
    return watermark_buff;
}

/**
 * 获取水印高度
 */
u8 watermark_get_height(void)
{
    return WATERMARK_HEIGHT;
}

/**
 * 获取水印宽度字节
 */
u8 watermark_get_width_bytes(void)
{
    return WATERMARK_WIDTH;
}


